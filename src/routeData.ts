import {
  defineRouteMiddleware,
  type StarlightRouteData,
} from '@astrojs/starlight/route-data';
import {
  getPagesByPath,
  labelOf,
  orderOf,
  withBase,
  withoutBase,
  type DocsEntry,
} from './lib/pages';

type Entry = StarlightRouteData['sidebar'][number];
type Link = Extract<Entry, { type: 'link' }>;
type Group = Extract<Entry, { type: 'group' }>;

const links = (entries: Entry[]): Link[] =>
  entries.flatMap((e) => (e.type === 'link' ? [e] : links(e.entries)));

/** The section index link of a group: the one whose path prefixes every other link. */
function indexLinkOf(group: Group) {
  const all = links(group.entries);
  return group.entries.find(
    (e): e is Link =>
      e.type === 'link' && all.every((l) => l.href.startsWith(e.href))
  );
}

/**
 * Autogenerated sidebar groups are named after their folder and ordered by
 * their lowest child. Instead, use the section index page (index.md) like Hugo
 * did: its title labels the group, its `order` positions the group, and it is
 * listed first as "Overview".
 */
function shapeGroup(
  group: Group,
  pages: Map<string, DocsEntry>,
  topLevel: boolean
) {
  // Sidebar hrefs include the base path, page keys don't
  const pageOf = (href: string) => pages.get(withoutBase(href));
  const index = indexLinkOf(group);
  const indexPage = index && pageOf(index.href);
  if (index && indexPage && !topLevel) group.label = labelOf(indexPage);

  const orderOfEntry = (e: Entry) =>
    e === index
      ? -Infinity
      : orderOf(
          pageOf(e.type === 'link' ? e.href : (indexLinkOf(e)?.href ?? ''))
        );
  group.entries.sort((a, b) => orderOfEntry(a) - orderOfEntry(b));

  group.entries = group.entries.map((e) => {
    if (e.type !== 'group') return e;
    shapeGroup(e, pages, false);
    // A section without visible child pages is just a link
    const [only] = e.entries;
    return e.entries.length === 1 && only.type === 'link'
      ? { ...only, label: e.label }
      : e;
  });

  for (const e of group.entries) {
    if (e.type === 'group') continue;
    if (e === index) e.label = 'Overview';
    const external = pageOf(e.href)?.data.externalLink;
    if (external) {
      e.href = external;
      e.attrs = {
        ...e.attrs,
        target: '_blank',
        rel: 'noopener',
        'data-external': '',
      };
    }
  }
}

export const onRequest = defineRouteMiddleware(async (context) => {
  const route = context.locals.starlightRoute;
  const pages = await getPagesByPath();

  // Hero buttons (splash pages) are not base-path aware
  for (const action of route.entry.data.hero?.actions ?? []) {
    const { link } = action;
    if (link.startsWith('/') && withoutBase(link) === link) {
      action.link = withBase(link);
    }
  }

  for (const entry of route.sidebar) {
    if (entry.type === 'group') shapeGroup(entry, pages, true);
  }

  // Pagination was computed from the unsorted sidebar; recompute it
  if (route.hasSidebar) {
    const flat = links(route.sidebar).filter((l) => !l.attrs['data-external']);
    const i = flat.findIndex((l) => l.isCurrent);
    if (i > -1) {
      route.pagination = { prev: flat[i - 1], next: flat[i + 1] };
    }
  }
});
